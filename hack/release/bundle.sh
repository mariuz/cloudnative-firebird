#!/usr/bin/env bash
# Writes the install manifest of the operator's version (hack/release/version.sh): the CRDs, then
# the namespace, ServiceAccount, RBAC, webhook and Deployment of config/deploy, in the order they
# apply, as one file (like CloudNativePG's cnpg-<version>.yaml). The Release workflow attaches it
# to the version's GitHub Release, so one kubectl apply installs or upgrades the operator. The
# PodMonitor (config/deploy/podmonitor.yaml, needs the Prometheus operator) is not included.
#
#   hack/release/bundle.sh [output file]   (default cloudnative-firebird-<version>.yaml)
set -euo pipefail

root="$(cd "$(dirname "${BASH_SOURCE[0]}")/../.." && pwd)"
version="$("$root/hack/release/version.sh")"
out="${1:-cloudnative-firebird-$version.yaml}"

files=("$root"/config/crds/*.yaml)
for f in namespace serviceaccount rbac webhook deployment; do
  files+=("$root/config/deploy/$f.yaml")
done

{
  echo "# cloudnative-firebird $version: the CRDs and the operator (namespace cloudnative-firebird-system)."
  echo "# Generated by hack/release/bundle.sh from config/crds and config/deploy; apply CRDs and all:"
  echo "#   kubectl apply -f cloudnative-firebird-$version.yaml"
  first=1
  for f in "${files[@]}"; do
    [ "$first" = 1 ] || echo "---"
    first=0
    echo "# $(realpath --relative-to="$root" "$f")"
    # a file opening with its own separator (rbac.yaml) would leave an empty document
    sed '1{/^---$/d}' "$f"
    # a file without a final newline would join the next separator
    [ -z "$(tail -c1 "$f")" ] || echo
  done
} > "$out"
echo "$out"
